#![no_std]
#![no_main]

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}

#[repr(C, packed)]
struct Input {
    selector: u64,
    a: u128,
    b: u128,
}

#[unsafe(no_mangle)]
pub fn entrypoint(input: *const Input) -> u64 {
    let Input { selector, a, b } = unsafe { core::ptr::read_volatile(input) };
    let result = match selector {
        0 => a / b,
        1 => a % b,
        2 => (a as i128 / b as i128) as u128,
        _ => (a as i128 % b as i128) as u128,
    };
    result as u64 ^ (result >> 64) as u64
}
