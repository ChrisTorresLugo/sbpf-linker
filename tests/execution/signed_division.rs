#![no_std]
#![no_main]

use core::ptr::read_volatile;

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}

fn reference_div(a: i64, b: i64) -> i64 {
    let quotient = a.unsigned_abs() / b.unsigned_abs();
    if (a < 0) != (b < 0) {
        0i64.wrapping_sub_unsigned(quotient)
    } else {
        quotient as i64
    }
}

fn reference_rem(a: i64, b: i64) -> i64 {
    let remainder = a.unsigned_abs() % b.unsigned_abs();
    if a < 0 { 0i64.wrapping_sub_unsigned(remainder) } else { remainder as i64 }
}

#[inline(never)]
fn div64(a: i64, b: i64) -> i64 {
    a.wrapping_div(b)
}

#[inline(never)]
fn rem64(a: i64, b: i64) -> i64 {
    a.wrapping_rem(b)
}

#[inline(never)]
fn div32(a: i32, b: i32) -> i32 {
    a.wrapping_div(b)
}

#[inline(never)]
fn rem32(a: i32, b: i32) -> i32 {
    a.wrapping_rem(b)
}

fn self_check(values: *const i64, count: usize) -> u64 {
    let mut comparisons = 0u64;
    let mut mismatches = 0u64;
    let mut compare = |actual: i64, expected: i64| {
        comparisons += 1;
        mismatches += u64::from(actual != expected);
    };
    for i in 0..count {
        for j in 0..count {
            let a = unsafe { read_volatile(values.add(i)) };
            let b = unsafe { read_volatile(values.add(j)) };
            if b != 0 {
                compare(div64(a, b), reference_div(a, b));
                compare(rem64(a, b), reference_rem(a, b));
            }
            let (a, b) = (a as i32, b as i32);
            if b != 0 {
                let (wide_a, wide_b) = (i64::from(a), i64::from(b));
                compare(
                    i64::from(div32(a, b)),
                    reference_div(wide_a, wide_b) as i32 as i64,
                );
                compare(
                    i64::from(rem32(a, b)),
                    reference_rem(wide_a, wide_b),
                );
            }
        }
    }
    comparisons << 32 | mismatches
}

#[unsafe(no_mangle)]
pub fn entrypoint(input: *const i64) -> u64 {
    let selector = unsafe { read_volatile(input) };
    let a = unsafe { read_volatile(input.add(1)) };
    let b = unsafe { read_volatile(input.add(2)) };
    let narrow = |value: i32| u64::from(value as u32);
    match selector {
        0 => div64(a, b) as u64,
        1 => rem64(a, b) as u64,
        2 => narrow(div32(a as i32, b as i32)),
        3 => narrow(rem32(a as i32, b as i32)),
        4 => (a / -7) as u64,
        5 => (a % 7) as u64,
        6 => narrow(a as i32 / -7),
        7 => narrow(a as i32 % 7),
        8 => (a / 1_000_000_007) as u64,
        9 => (a % -1_000_000_007) as u64,
        _ => self_check(unsafe { input.add(2) }, a as usize),
    }
}
